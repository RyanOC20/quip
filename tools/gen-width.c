/* Generate src/width.h, the table of code points that take zero or two
 * terminal cells, from the C library's wcwidth().
 *
 * quip does not call wcwidth() at run time: its answers depend on the
 * locale and on how old the C library is, and the cursor must agree with
 * what the terminal draws whatever the user's locale. So the table is
 * generated once from a recent glibc and committed:
 *
 *   docker run --rm -v "$PWD":/w -w /w ubuntu:24.04 sh -c \
 *     'apt-get -qq update && apt-get -qq install -y gcc libc6-dev &&
 *      gcc -O2 -o /tmp/gen-width tools/gen-width.c && /tmp/gen-width > src/width.h'
 *
 * Code points wcwidth() calls unprintable (unassigned ones, mostly) may join
 * a range when it continues past them, which keeps the table short. Each
 * entry packs the first code point in the high 21 bits and the length minus
 * one in the low 11, so a long range takes several entries. */
#define _XOPEN_SOURCE 700
#include <locale.h>
#include <stdio.h>
#include <wchar.h>

#define CP_MAX 0x110000

static int cls[CP_MAX];

static void table(const char *name, int want) {
    int n = 0;
    printf("static const uint32_t %s[] = {\n", name);
    for (int cp = 0xA0; cp < CP_MAX; cp++) {
        if (cls[cp] != want) continue;
        int end = cp;
        for (int k = cp + 1; k < CP_MAX; k++) {
            if (cls[k] == want)
                end = k;
            else if (cls[k] != -1)
                break;
        }
        for (int s = cp; s <= end; s += 2048) {
            int len = end - s + 1 > 2048 ? 2048 : end - s + 1;
            printf("%s0x%08x,", n % 6 ? " " : "    ", (unsigned)(s << 11 | (len - 1)));
            if (++n % 6 == 0) printf("\n");
        }
        cp = end;
    }
    if (n % 6) printf("\n");
    printf("};\n");
}

int main(void) {
    if (!setlocale(LC_CTYPE, "C.UTF-8")) {
        fprintf(stderr, "gen-width: no C.UTF-8 locale\n");
        return 1;
    }
    for (int cp = 0; cp < CP_MAX; cp++) cls[cp] = cp < 0xA0 ? 1 : wcwidth((wchar_t)cp);
    printf("/* Generated by tools/gen-width.c from glibc's wcwidth(); do not edit. */\n"
           "/* clang-format off */\n");
    table("width_zero", 0);
    table("width_wide", 2);
    printf("/* clang-format on */\n");
    return 0;
}
